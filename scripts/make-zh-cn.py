"""Regenerate src/i18n/locales/zh-CN.ts from zh-TW.ts (character-level Traditional → Simplified, OpenCC t2s).
Character-level only, so names of departments, buildings and offices keep their wording.
Run: pip install opencc-python-reimplemented && python3 scripts/make-zh-cn.py"""
import pathlib, re, opencc
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'src/i18n/locales/zh-TW.ts').read_text(encoding='utf-8')
conv = opencc.OpenCC('t2s')
out = conv.convert(src)
out = out.replace('// Generated from the translation store; edit keys here directly is fine.',
                  '// Generated by scripts/make-zh-cn.py from zh-TW.ts — do not edit by hand, re-run the script.')
out = re.sub(r'\bconst zh = \{', 'const zhCN = {', out, count=1).replace('export default zh;', 'export default zhCN;')
(root / 'src/i18n/locales/zh-CN.ts').write_text(out, encoding='utf-8')
print('ok', len(out))
